// repositories/ReportRepository.js

class ReportRepository {
    constructor(pool) {
        // pool is the shared Singleton PgPool instance
        this.pool = pool
    }

    /**
     * Retrieves a single report record by their unique identifier.
     * 
     * @param {number} reportId - The unique identifier of the report.
     * @returns {Promise<Object|null>} The report record, or null if no report record exists with the given ID.
     */
    async findById(reportId) {
        const result = await this.pool.query(
            `SELECT "report_id", "manager_id", "date_generated", "period_start", "period_end"
            FROM donor_reports 
            WHERE "report_id" = $1`,
            [reportId]
        );
        return result.rows[0] || null;
    }

    /**
     * Finds every report generated by a specific manager. 
     * 
     * @param {number} managerId - The unique identifier of the manager. 
     * @returns {Promise<Array<Object>>} A list of reports that corresponds with the manager ID,
     *  ordered by date generated in descending order.
     */
    async findByManagerId(managerId) {
    const result = await this.pool.query(
      `SELECT "report_id", "manager_id", "date_generated", "period_start", "period_end"
      FROM donor_reports 
      WHERE "manager_id" = $1 
      ORDER BY "date_generated" DESC`,
      [managerId]
    );
    return result.rows;
  }

  /**
     * Creates a new report record.
     *
     * @param {Object} params - The new report's details.
     * @param {number} params.managerId - The unique identifier of the manager.
     * @param {string} params.periodStart - The starting period in the report.
     * @param {string} params.periodEnd - The ending period in the report.
     * @returns {Promise<Object>} The newly created report record.
     */
  async create({ managerId, periodStart, periodEnd }) {
    const result = await this.pool.query(
      `INSERT INTO donor_reports ("manager_id", "period_start", "period_end")
       VALUES ($1, $2, $3)
       RETURNING "report_id", "manager_id", "date_generated", "period_start", "period_end"`,
      [managerId, periodStart, periodEnd]
    );
    return result.rows[0];
  }
}

module.exports = ReportRepository;